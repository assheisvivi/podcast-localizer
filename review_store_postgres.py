"""Neon/PostgreSQL review sessions and atomic daily provider-call limits."""

from __future__ import annotations

import json
import os
import threading
import time
from contextlib import contextmanager
from datetime import datetime, timezone
from typing import Iterator


SESSION_LIFETIME_SECONDS = 7 * 24 * 60 * 60
_schema_lock = threading.Lock()
_schema_fingerprint: int | None = None


def _ensure_schema(db, dsn: str) -> None:
    global _schema_fingerprint
    fingerprint = hash(dsn)
    if _schema_fingerprint == fingerprint:
        return
    with _schema_lock:
        if _schema_fingerprint == fingerprint:
            return
        db.execute(
            "CREATE TABLE IF NOT EXISTS sessions ("
            "id TEXT PRIMARY KEY, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, "
            "expires_at BIGINT NOT NULL, payload TEXT NOT NULL)"
        )
        db.execute(
            "CREATE TABLE IF NOT EXISTS review_events ("
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "session_id TEXT NOT NULL, changed_at TEXT NOT NULL, segment_id TEXT NOT NULL, "
            "before_json TEXT NOT NULL, after_json TEXT NOT NULL)"
        )
        db.execute(
            "CREATE TABLE IF NOT EXISTS daily_usage ("
            "day_utc TEXT NOT NULL, action TEXT NOT NULL, used INTEGER NOT NULL, "
            "PRIMARY KEY (day_utc, action))"
        )
        db.commit()
        _schema_fingerprint = fingerprint


@contextmanager
def database() -> Iterator:
    import psycopg
    from psycopg.rows import dict_row

    dsn = os.environ["DATABASE_URL"]
    with psycopg.connect(dsn, row_factory=dict_row, connect_timeout=20, sslmode="require") as db:
        _ensure_schema(db, dsn)
        yield db


def ensure_ready() -> None:
    with database():
        pass


def create_session(session_id: str, payload: dict) -> None:
    now = int(time.time())
    with database() as db:
        db.execute(
            "DELETE FROM review_events WHERE session_id IN "
            "(SELECT id FROM sessions WHERE expires_at <= %s)",
            (now,),
        )
        db.execute("DELETE FROM sessions WHERE expires_at <= %s", (now,))
        db.execute("DELETE FROM daily_usage WHERE day_utc < %s", (datetime.now(timezone.utc).date().isoformat(),))
        db.execute(
            "INSERT INTO sessions (id, created_at, updated_at, expires_at, payload) "
            "VALUES (%s, %s, %s, %s, %s)",
            (session_id, now, now, now + SESSION_LIFETIME_SECONDS, json.dumps(payload, ensure_ascii=False)),
        )


def get_session(session_id: str) -> dict | None:
    with database() as db:
        row = db.execute(
            "SELECT payload FROM sessions WHERE id = %s AND expires_at > %s",
            (session_id, int(time.time())),
        ).fetchone()
    return json.loads(row["payload"]) if row else None


def update_session(session_id: str, payload: dict, changes: list[tuple[str, dict, dict]]) -> bool:
    now = int(time.time())
    changed_at = datetime.now(timezone.utc).isoformat()
    with database() as db:
        current = db.execute(
            "SELECT id FROM sessions WHERE id = %s AND expires_at > %s FOR UPDATE",
            (session_id, now),
        ).fetchone()
        if not current:
            return False
        db.execute(
            "UPDATE sessions SET payload = %s, updated_at = %s WHERE id = %s",
            (json.dumps(payload, ensure_ascii=False), now, session_id),
        )
        for segment_id, before, after in changes:
            db.execute(
                "INSERT INTO review_events (session_id, changed_at, segment_id, before_json, after_json) "
                "VALUES (%s, %s, %s, %s, %s)",
                (
                    session_id, changed_at, segment_id,
                    json.dumps(before, ensure_ascii=False), json.dumps(after, ensure_ascii=False),
                ),
            )
    return True


def review_events(session_id: str) -> list[dict]:
    with database() as db:
        rows = db.execute(
            "SELECT changed_at, segment_id, before_json, after_json "
            "FROM review_events WHERE session_id = %s ORDER BY id",
            (session_id,),
        ).fetchall()
    return [
        {
            "changed_at": row["changed_at"],
            "segment_id": row["segment_id"],
            "before": json.loads(row["before_json"]),
            "after": json.loads(row["after_json"]),
        }
        for row in rows
    ]


def consume_daily_quota(action: str, limit: int) -> bool:
    if limit <= 0:
        return False
    day = datetime.now(timezone.utc).date().isoformat()
    with database() as db:
        row = db.execute(
            "INSERT INTO daily_usage (day_utc, action, used) VALUES (%s, %s, 1) "
            "ON CONFLICT (day_utc, action) DO UPDATE SET used = daily_usage.used + 1 "
            "WHERE daily_usage.used < %s RETURNING used",
            (day, action, limit),
        ).fetchone()
    return row is not None
